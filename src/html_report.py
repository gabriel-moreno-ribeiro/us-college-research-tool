# --- SVG Chart Generators ---

def _chart_net_price_by_income(metrics: dict[str, Any]) -> str:
    """Generate SVG bar chart of net price by income bracket."""
    brackets = [
        ("$0-30k", "net_price_0_30k"),
        ("$30-48k", "net_price_30_48k"),
        ("$48-75k", "net_price_48_75k"),
        ("$75-110k", "net_price_75_110k"),
        ("$110k+", "net_price_110k_plus"),
    ]
    values = []
    for label, key in brackets:
        m = metrics.get(key, {})
        val = m.get("value") if isinstance(m, dict) else None
        values.append((label, val))

    # Filter out None values
    valid = [(l, v) for l, v in values if v is not None]
    if not valid:
        return ""

    max_val = max(v for _, v in valid)
    if max_val == 0:
        return ""

    bar_width = 80
    bar_gap = 10
    chart_width = len(valid) * (bar_width + bar_gap) + 60
    chart_height = 200
    max_bar_height = 150

    bars = []
    for i, (label, val) in enumerate(valid):
        x = 50 + i * (bar_width + bar_gap)
        bar_height = (val / max_val) * max_bar_height
        y = chart_height - 30 - bar_height
        bars.append(
            f'<rect x="{x}" y="{y}" width="{bar_width}" height="{bar_height}" fill="#2563eb" rx="3"/>'
            f'<text x="{x + bar_width/2}" y="{y - 5}" text-anchor="middle" font-size="11" fill="#1a1a1a">${val:,.0f}</text>'
            f'<text x="{x + bar_width/2}" y="{chart_height - 10}" text-anchor="middle" font-size="10" fill="#6b7280">{label}</text>'
        )

    # Add sticker price line if available
    sticker = metrics.get("tuition_out_of_state", {})
    sticker_val = sticker.get("value") if isinstance(sticker, dict) else None
    sticker_line = ""
    if sticker_val and sticker_val > max_val:
        max_val = sticker_val
        # Recalculate bars with new max
        bars = []
        for i, (label, val) in enumerate(valid):
            x = 50 + i * (bar_width + bar_gap)
            bar_height = (val / max_val) * max_bar_height
            y = chart_height - 30 - bar_height
            bars.append(
                f'<rect x="{x}" y="{y}" width="{bar_width}" height="{bar_height}" fill="#2563eb" rx="3"/>'
                f'<text x="{x + bar_width/2}" y="{y - 5}" text-anchor="middle" font-size="11" fill="#1a1a1a">${val:,.0f}</text>'
                f'<text x="{x + bar_width/2}" y="{chart_height - 10}" text-anchor="middle" font-size="10" fill="#6b7280">{label}</text>'
            )
        sticker_y = chart_height - 30 - (sticker_val / max_val) * max_bar_height
        sticker_line = (
            f'<line x1="45" y1="{sticker_y}" x2="{chart_width - 10}" y2="{sticker_y}" stroke="#ef4444" stroke-width="1.5" stroke-dasharray="5,3"/>'
            f'<text x="{chart_width - 10}" y="{sticker_y - 5}" text-anchor="end" font-size="10" fill="#ef4444">Sticker: ${sticker_val:,.0f}</text>'
        )

    return f"""<div class="chart-container">
<h3>Net Price by Family Income</h3>
<svg width="{chart_width}" height="{chart_height}" viewBox="0 0 {chart_width} {chart_height}">
{"".join(bars)}
{sticker_line}
</svg>
<p style="font-size:0.75rem;color:#6b7280;">Source: College Scorecard. Reflects domestic students with financial aid. International aid varies.</p>
</div>"""


def _provenance_badge(data: dict[str, Any]) -> str:
    """Generate provenance badge HTML."""
    source_type = data.get("source_type", "unknown")
    confidence = data.get("confidence", "low")

    type_class = {
        "official": "badge-official",
        "unofficial": "badge-unofficial",
        "estimated": "badge-estimated",
    }.get(source_type, "badge-estimated")

    conf_class = {
        "high": "badge-high",
        "medium": "badge-medium",
        "low": "badge-low",
    }.get(confidence, "badge-low")

    badges = f'<span class="badge {type_class}">{source_type}</span>'
    if confidence != "high":
        badges += f' <span class="badge {conf_class}">{confidence} confidence</span>'
    return badges


def _write_contacts_csv(contacts: list[dict[str, str]], path: Path) -> None:
    """Write contacts to CSV."""
    if not contacts:
        path.write_text("name,role,email,linkedin,orcid,priority,university\n", encoding="utf-8")
        return

    lines = ["name,role,email,linkedin,orcid,priority,university"]
    for c in contacts:
        row = [
            c.get("name", ""),
            c.get("role", ""),
            c.get("email", ""),
            c.get("linkedin", ""),
            c.get("orcid", ""),
            c.get("priority", ""),
            c.get("university", ""),
        ]
        lines.append(",".join(f'"{v}"' for v in row))
    path.write_text("\n".join(lines), encoding="utf-8")
