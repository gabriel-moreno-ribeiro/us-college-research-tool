def _section_faculty(data: dict[str, Any]) -> dict[str, str]:
    professors = data if isinstance(data, list) else data.get("professors", [])
    rows = []
    for p in professors[:20]:
        name = p.get("name", "")
        title = p.get("title", "")
        email = p.get("email", "")
        score = p.get("relevance_score", "")
        email_link = f'<a href="mailto:{email}">{email}</a>' if email else ""
        rows.append(f"<tr><td><strong>{html.escape(name)}</strong></td><td>{html.escape(title)}</td><td>{email_link}</td><td>{score}</td></tr>")

    return {
        "id": "faculty",
        "title": "Faculty & Research",
        "html": f"""<section id="faculty">
<h2>Faculty & Research</h2>
<table><thead><tr><th>Name</th><th>Title</th><th>Email</th><th>Relevance</th></tr></thead>
<tbody>{"".join(rows)}</tbody></table>
</section>""",
    }


def _section_opportunities(data: dict[str, Any]) -> dict[str, str]:
    items = []
    if isinstance(data, dict):
        for category, opps in data.items():
            if not isinstance(opps, list):
                continue
            items.append(f"<h3>{html.escape(category)}</h3><ul>")
            for o in opps:
                name = o.get("name", "")
                desc = o.get("description", "")
                url = o.get("source_url", "")
                link = f' — <a href="{url}">source</a>' if url else ""
                items.append(f"<li><strong>{html.escape(name)}</strong>: {html.escape(desc)}{link}</li>")
            items.append("</ul>")

    return {"id": "opportunities", "title": "Opportunities", "html": f'<section id="opportunities"><h2>Opportunities</h2>{"".join(items)}</section>'}


