def _build_toc(sections: list[dict[str, str]]) -> str:
    """Build table of contents from sections."""
    items = []
    for s in sections:
        items.append(f'<li><a href="#{s["id"]}">{html.escape(s["title"])}</a></li>')
    return f"<ul>{''.join(items)}</ul>"


def _section_overview(data: dict[str, Any]) -> dict[str, str]:
    """Institutional overview section."""
    metrics = data.get("metrics", {})
    rows = []
    for key, m in metrics.items():
        if not isinstance(m, dict) or m.get("value") is None:
            continue
        val = m["value"]
        label = m.get("label", key)
        if isinstance(val, float) and val < 1:
            display = f"{val * 100:.1f}%"
        elif isinstance(val, (int, float)) and val > 1000:
            display = f"${val:,.0f}"
        else:
            display = str(val)
        rows.append(f"<tr><td>{html.escape(label)}</td><td><strong>{display}</strong></td></tr>")

    # Net price by income chart
    chart = _chart_net_price_by_income(metrics)

    return {
        "id": "overview",
        "title": "Institutional Overview",
        "html": f"""<section id="overview">
<h2>Institutional Overview</h2>
<table><thead><tr><th>Metric</th><th>Value</th></tr></thead>
<tbody>{"".join(rows)}</tbody></table>
{chart}
<div class="alert alert-warning">Data from College Scorecard (U.S. Department of Education). Has 2-3 year lag from current year.</div>
</section>""",
    }


