"""
HTML report generator with inline SVG charts.

Generates a single self-contained HTML file with:
- Inline CSS (no external deps)
- SVG charts generated in Python
- Print-friendly @media print styles
- Provenance badges on non-official data
- Table of contents with anchors
"""
from __future__ import annotations

import html
import json
from datetime import datetime
from pathlib import Path
from typing import Any

OUTPUT_DIR = Path(__file__).parent.parent / "output"


def generate_html_report(
    report_data: dict[str, Any],
    language: str = "en",
    output_path: Path | None = None,
) -> dict[str, str]:
    """Generate complete HTML report from structured data.

    Returns dict with file paths written:
    - report.html
    - report_data.json
    - sources.txt
    - contacts.csv
    """
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    uni_slug = report_data.get("university", "report").lower().replace(" ", "_")
    out_dir = output_path or OUTPUT_DIR / uni_slug
    out_dir.mkdir(parents=True, exist_ok=True)

    # Write report_data.json (source of truth)
    data_path = out_dir / "report_data.json"
    data_path.write_text(json.dumps(report_data, indent=2, ensure_ascii=False, default=str), encoding="utf-8")

    # Generate HTML
    html_content = _build_html(report_data, language)
    html_path = out_dir / "report.html"
    html_path.write_text(html_content, encoding="utf-8")

    # Generate sources.txt
    sources = report_data.get("sources", [])
    sources_path = out_dir / "sources.txt"
    sources_path.write_text("\n".join(s.get("url", "") for s in sources if s.get("url")), encoding="utf-8")

    # Generate contacts.csv
    contacts = report_data.get("contacts", [])
    csv_path = out_dir / "contacts.csv"
    _write_contacts_csv(contacts, csv_path)

    return {
        "report_html": str(html_path),
        "report_data_json": str(data_path),
        "sources_txt": str(sources_path),
        "contacts_csv": str(csv_path),
    }


def _build_html(data: dict[str, Any], language: str) -> str:
    """Build the complete HTML document."""
    uni_name = data.get("university", "University Report")
    sections = []

    # Build sections from available data
    if "overview" in data:
        sections.append(_section_overview(data["overview"]))
    if "rankings" in data:
        sections.append(_section_rankings(data["rankings"]))
    if "international" in data:
        sections.append(_section_international(data["international"]))
    if "english_requirements" in data:
        sections.append(_section_english(data["english_requirements"]))
    if "faculty" in data:
        sections.append(_section_faculty(data["faculty"]))
    if "opportunities" in data:
        sections.append(_section_opportunities(data["opportunities"]))
    if "career_outcomes" in data:
        sections.append(_section_career(data["career_outcomes"]))
    if "alumni" in data:
        sections.append(_section_alumni(data["alumni"]))
    if "community" in data:
        sections.append(_section_community(data["community"]))
    if "visa_pathways" in data:
        sections.append(_section_visa(data["visa_pathways"]))
    if "application" in data:
        sections.append(_section_application(data["application"]))

    # Table of contents
    toc = _build_toc(sections)

    generated_at = datetime.now().strftime("%Y-%m-%d %H:%M")

    return f"""<!DOCTYPE html>
<html lang="{language}">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{html.escape(uni_name)} — Research Report</title>
<style>
{_get_css()}
</style>
</head>
<body>
<header>
<h1>{html.escape(uni_name)}</h1>
<p class="subtitle">Undergraduate Application Research Report</p>
<p class="meta">Generated: {generated_at} | Data sources: College Scorecard, ORCID, Semantic Scholar, web search</p>
</header>
<nav id="toc">
<h2>Contents</h2>
{toc}
</nav>
<main>
{"".join(s["html"] for s in sections)}
</main>
<footer>
<p>Generated by US College Research Tool. Data has provenance markers — verify non-official sources independently.</p>
</footer>
</body>
</html>"""


