def _section_international(data: dict[str, Any]) -> dict[str, str]:
    items = []
    d = data.get("data", {})
    if "need_blind_international" in d:
        policy = d["need_blind_international"]
        val = policy.get("value", "unknown") if isinstance(policy, dict) else policy
        badge = _provenance_badge(policy) if isinstance(policy, dict) else ""
        items.append(f"<tr><td>Need-blind for internationals?</td><td><strong>{val}</strong> {badge}</td></tr>")
    if "aid_first_year_only" in d:
        policy = d["aid_first_year_only"]
        val = policy.get("value", "unknown") if isinstance(policy, dict) else policy
        badge = _provenance_badge(policy) if isinstance(policy, dict) else ""
        alert = '<div class="alert alert-warning">Aid only available at freshman admission. Cannot apply later.</div>' if val else ""
        items.append(f"<tr><td>Aid only at first year?</td><td><strong>{val}</strong> {badge}</td></tr>")

    return {
        "id": "international",
        "title": "International Admissions",
        "html": f"""<section id="international">
<h2>International Admissions</h2>
<table><thead><tr><th>Policy</th><th>Status</th></tr></thead>
<tbody>{"".join(items)}</tbody></table>
{alert if 'alert' in dir() else ''}
</section>""",
    }


